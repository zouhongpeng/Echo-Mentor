/** 生成阶段打法提示词段落（stage 无效时返回空串） */
export function buildStageSection(stage?: string): string {
  if (!stage) return "";
  const pb = (STAGE_PLAYBOOK as Record<string, { goal: string; dos: string[]; donts: string[] }>)[stage];
  if (!pb) return "";
  return [
    `【当前关系阶段：${stage}（用户手动指定，优先级高于你的自动判断）】`,
    `阶段目标：${pb.goal}`,
    "这个阶段应该做的：",
    ...pb.dos.map((d) => `- ${d}`),
    "这个阶段的雷区（建议回复必须避开）：",
    ...pb.donts.map((d) => `- ${d}`),
    "你的所有建议必须符合这个阶段的节奏：太快的建议视为不合格，并在 stage_tip 里给出更贴合阶段的推进方式。",
  ].join("\n");
}
