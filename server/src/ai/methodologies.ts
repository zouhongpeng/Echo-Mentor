/** 构建注入系统提示词的话术库区块 */
export function buildPhraseSection(): string {
  const scenePart = Object.entries(REPLY_PHRASES)
    .map(([scene, styles]) => {
      const body = Object.entries(styles)
        .map(([style, phrases]) => `  · ${style}：${phrases.join(" / ")}`)
        .join("\n");
      return `【${scene}】\n${body}`;
    })
    .join("\n");
  const intentPart = Object.entries(INTENT_PHRASES)
    .map(([intent, v]) => `【${intent}】${v.tip}\n  · ${v.phrases.join(" / ")}`)
    .join("\n");
  return `【回复话术参考库】\n一、按场景：\n${scenePart}\n\n二、按意图：\n${intentPart}\n\n使用规范：以上仅为句式参考，必须结合当前对话的上下文与人物背景改写后化用，禁止原样照抄生搬硬套；语气必须与聊天记录匹配。`;
}

